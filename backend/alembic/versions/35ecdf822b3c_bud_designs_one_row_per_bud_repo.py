"""bud designs one row per bud repo

The old ``uq_bud_design_bud_repo`` treated NULLs as distinct, so concurrent
upserts could store several BUD-level (``repo_id IS NULL``) designs for one
BUD. The replacement constraint is ``NULLS NOT DISTINCT``.

Existing duplicates are collapsed first. Per (bud_id, repo_id) the kept row
is the most recently updated one that has design HTML, or the most recently
updated one if none do, so an empty pending/failed duplicate never wins over
a generated wireframe. Chat messages pointing at a dropped duplicate move to
the kept row. Section sessions move too where that doesn't clash with a
session the kept row already has; any leftover sessions go with the
duplicate through the ``ON DELETE CASCADE``. Their messages stay in the
table but, like a thread rotated out at the message cap, are no longer the
active thread that chat history shows.

Revision ID: 35ecdf822b3c
Revises: cd396fa01ec6
Create Date: 2026-10-22 16:39:29.013460

"""

