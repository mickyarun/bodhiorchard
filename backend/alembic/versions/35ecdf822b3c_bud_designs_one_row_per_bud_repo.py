def _collapse_duplicate_designs() -> None:
    """Keep one design per (bud_id, repo_id) and repoint references to it."""
    # PARTITION BY groups NULL repo_ids together, which is exactly the key
    # the new constraint enforces. Rows with HTML sort ahead of empty ones.
    op.execute(
        "CREATE TEMP TABLE bud_design_dupes AS "
        "SELECT id AS dup_id, keep_id FROM ("
        "  SELECT id, "
        "    first_value(id) OVER w AS keep_id, "
        "    row_number() OVER w AS rn "
        "  FROM bud_designs "
        "  WINDOW w AS (PARTITION BY bud_id, repo_id "
        "               ORDER BY (design_html IS NOT NULL) DESC, "
        "                        updated_at DESC, created_at DESC, id DESC)"
        ") ranked WHERE rn > 1"
    )
    op.execute(
        "UPDATE bud_chat_messages m SET design_id = d.keep_id "
        "FROM bud_design_dupes d WHERE m.design_id = d.dup_id"
    )
    # One session per (bud, section, design) is allowed, so move at most one
    # duplicate's session per section, and only when the kept row has none.
    op.execute(
        "UPDATE bud_section_sessions s SET design_id = d.keep_id "
        "FROM bud_design_dupes d "
        "WHERE s.design_id = d.dup_id "
        "  AND s.id IN ("
        "    SELECT DISTINCT ON (d2.keep_id, s2.section) s2.id "
        "    FROM bud_section_sessions s2 "
        "    JOIN bud_design_dupes d2 ON s2.design_id = d2.dup_id "
        "    ORDER BY d2.keep_id, s2.section, s2.updated_at DESC"
        "  ) "
        "  AND NOT EXISTS ("
        "    SELECT 1 FROM bud_section_sessions k "
        "    WHERE k.design_id = d.keep_id AND k.section = s.section"
        "  )"
    )
    op.execute("DELETE FROM bud_designs b USING bud_design_dupes d WHERE b.id = d.dup_id")
    op.execute("DROP TABLE bud_design_dupes")


